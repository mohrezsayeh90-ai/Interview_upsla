#!/usr/bin/env python3
"""Train once using a discrete Dirichlet-energy PINN loss, without training labels.

Only validation networks call the sparse reference solver. The test set is
generated by evaluate.py from a different SeedSequence stream after selection.
"""
import argparse
import hashlib
import json
import sys
import time
from pathlib import Path
import numpy as np
import pandas as pd
import torch

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT));sys.path.insert(0,str(ROOT/'src'))
from parametric_pinn.model import Preprocessor,ParametricPINN,stack_prepared

OUT=ROOT/'parametric_pinn'
SEED=20261105


def generate(count,stream,n=25,reference=False):
    rng=np.random.default_rng(np.random.SeedSequence([SEED,stream]))
    pre=Preprocessor(n)
    rows=[];refs=[];meta=[];attempts=0
    t=time.perf_counter()
    while len(rows)<count:
        # Mixture covers main-scenario endpoints and the full continuous domain.
        delta=float(rng.choice([0.,.1,.25])) if rng.random()<.5 else rng.uniform(0,.25)
        sigma=float(rng.choice([0.,1.,2.])) if rng.random()<.5 else rng.uniform(0,2)
        p=.5+delta*rng.uniform(-1,1)
        g=pre.grid.generate(p,sigma,rng)
        row=pre.prepare(g,delta,p,sigma)
        attempts+=1
        if not row.spanning:continue
        rows.append(row)
        meta.append([delta,p,sigma])
        if reference:
            r=pre.grid.solve(g,details=True)
            refs.append((r.conductance,np.nan_to_num(r.heads,nan=0)))
    batch=stack_prepared(rows)
    fingerprint=hashlib.sha256(np.stack([r.g for r in rows]).tobytes()).hexdigest()
    info={'seed':SEED,'stream':stream,'retained_spanning':count,'generated':attempts,
          'elapsed_seconds':time.perf_counter()-t,'g_sha256_float64':fingerprint}
    exact=None
    if reference:
        exact={'geff':np.array([r[0] for r in refs]),'heads':np.stack([r[1] for r in refs])}
        # Keep original float64 conductances for stringent validation.
        batch=stack_prepared(rows,dtype=torch.float64)
    return batch,exact,info


@torch.inference_mode()
def validate(model,data,exact,depth=256,batch_size=64,learned=True):
    model=model.double().eval()
    energies=[];heads=[]
    for start in range(0,len(exact['geff']),batch_size):
        batch={k:v[start:start+batch_size] for k,v in data.items()}
        h=model(batch,depth=depth,learned=learned)
        energies.append(model.energy(batch,h).numpy());heads.append(h.numpy())
    energy=np.concatenate(energies)
    hp=np.concatenate(heads)
    rel=np.maximum(0,energy/exact['geff']-1)
    valid=data['free'].numpy()
    head_mse=((hp-exact['heads'])**2*valid).sum(1)/np.maximum(valid.sum(1),1)
    return {'depth':depth,'mean_relative_g_error':float(rel.mean()),
            'median_relative_g_error':float(np.median(rel)),
            'p95_relative_g_error':float(np.quantile(rel,.95)),
            'p99_relative_g_error':float(np.quantile(rel,.99)),
            'maximum_relative_g_error':float(rel.max()),
            'head_rmse':float(np.sqrt(head_mse.mean()))}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--train',type=int,default=4096)
    parser.add_argument('--validation',type=int,default=512)
    parser.add_argument('--epochs',type=int,default=16)
    parser.add_argument('--batch',type=int,default=32)
    parser.add_argument('--threads',type=int,default=2)
    args=parser.parse_args()
    torch.set_num_threads(args.threads);torch.manual_seed(SEED)
    (OUT/'models').mkdir(exist_ok=True);(OUT/'results').mkdir(exist_ok=True)
    start=time.perf_counter()
    train,_,train_info=generate(args.train,101,reference=False)
    validation,exact,val_info=generate(args.validation,102,reference=True)
    print('datasets',json.dumps({'train':train_info,'validation':val_info}),flush=True)
    model=ParametricPINN()
    config={'n':25,'width':32,'depth':256}
    torch.save({'config':config,'state_dict':model.state_dict()},OUT/'models/untrained_control.pt')
    untrained=validate(model,validation,exact)
    (OUT/'results/untrained_validation.json').write_text(json.dumps(untrained,indent=2)+'\n')
    model=model.float().train()
    optimizer=torch.optim.Adam(model.parameters(),lr=.0015,weight_decay=1e-7)
    order_generator=torch.Generator().manual_seed(SEED+1)
    best=float('inf');history=[]
    train_start=time.perf_counter()
    for epoch in range(args.epochs):
        phase=(epoch+.5)/args.epochs
        depth=32 if phase<.1875 else (64 if phase<.4375 else (128 if phase<.6875 else 256))
        model.float().train()
        order=torch.randperm(args.train,generator=order_generator)
        total=0.;gradnorm=0.
        epoch_start=time.perf_counter()
        for offset in range(0,args.train,args.batch):
            indices=order[offset:offset+args.batch]
            batch={k:v[indices] for k,v in train.items()}
            predicted=model(batch,depth=depth)
            energy=model.energy(batch,predicted)
            initial=model.energy(batch,batch['h0']).detach().clamp_min(1e-20)
            # log is monotone: for every individual network the unique minimum
            # on the free connected component is the Kirchhoff solution.
            residual=model.residual(batch,predicted)
            loss=torch.log(energy.clamp_min(1e-20)/initial).mean()+.01*residual.square().mean()
            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            norm=torch.nn.utils.clip_grad_norm_(model.parameters(),1.)
            optimizer.step()
            total+=float(loss.detach())*len(indices)
            gradnorm+=float(norm)
        stats=validate(model,validation,exact,depth=256)
        row={'epoch':epoch+1,'train_depth':depth,'physics_loss':total/args.train,
             'gradient_norm_sum':gradnorm,'epoch_seconds':time.perf_counter()-epoch_start,**stats}
        history.append(row)
        pd.DataFrame(history).to_csv(OUT/'results/training_history.csv',index=False)
        if stats['mean_relative_g_error']<best:
            best=stats['mean_relative_g_error']
            torch.save({'config':config,'state_dict':model.float().state_dict()},OUT/'models/parametric_pinn.pt')
            best_epoch=epoch+1
        print(json.dumps(row),flush=True)
    training_seconds=time.perf_counter()-train_start
    state=torch.load(OUT/'models/parametric_pinn.pt',weights_only=True)
    model.load_state_dict(state['state_dict']);model.double().eval()
    validation_depths=[]
    for depth in [0,32,64,128,256,512,1024,2048]:
        stats=validate(model,validation,exact,depth=depth)
        validation_depths.append(stats)
        print('depth validation',json.dumps(stats),flush=True)
    pd.DataFrame(validation_depths).to_csv(OUT/'results/validation_depths.csv',index=False)
    # Accuracy mode fixed from validation alone; no per-test stopping rule.
    eligible=[x for x in validation_depths if x['depth']>=256 and x['p99_relative_g_error']<.001]
    accurate_depth=eligible[0]['depth'] if eligible else 2048
    manifest={'seed':SEED,'arguments':vars(args),'config':config,'best_epoch':best_epoch,
              'training_seconds':training_seconds,'elapsed_seconds':time.perf_counter()-start,
              'train_data':train_info,'validation_data':val_info,
              'fast_depth':256,'accurate_depth':accurate_depth,
              'validation_p99_target':.001,
              'validation_p99_target_met':bool(eligible),
              'accurate_depth_rule':'smallest tested depth >=256 with validation p99 relative G error <0.001, else the tested cap 2048; target success is explicitly recorded',
              'torch':torch.__version__,'numpy':np.__version__,'device':'CPU',
              'parameters':sum(p.numel() for p in model.parameters()),
              'loss':'mean log(Dirichlet energy / initial geodesic energy) + 0.01 mean normalized Kirchhoff residual squared',
              'training_reference_labels':False,'selection':'minimum validation mean relative energy-derived conductance error at depth 256',
              'inference':'fixed-depth learned residual graph network; fixed iterative head updates per input, no sparse solve or per-input weight fitting; explicit component and Dijkstra preprocessing'}
    (OUT/'results/training_manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps(manifest,indent=2),flush=True)


if __name__=='__main__':main()
